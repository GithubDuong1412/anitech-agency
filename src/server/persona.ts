import fs from "node:fs";
import path from "node:path";
import type { Agent, AgentRole, Department } from "@/lib/roster";

const MAX_PERSONA_CHARS = 12_000;
const cache = new Map<string, string>();

/** Rule files are named after the character (e.g. sasuke-backend). Anything else is refused. */
const RULE_NAME = /^[a-z0-9][a-z0-9-]*$/;

function stripFrontmatter(text: string): string {
  const normalized = text.replace(/\r\n?/g, "\n");
  const match = normalized.match(/^---\n[\s\S]*?\n---\n?/);
  return (match ? normalized.slice(match[0].length) : normalized).trim();
}

/**
 * The agent's own rules: .cursor/rules/<rule>.mdc, generated by `npm run sync:agents`
 * from agents/personas/<id>.md plus the upstream skill. This is the agent's knowledge.
 */
export function loadPersona(agent: Agent, root = process.cwd()): string {
  const key = `${root}::${agent.rule}`;
  const cached = cache.get(key);
  if (cached !== undefined) return cached;
  let text = "";
  if (RULE_NAME.test(agent.rule)) {
    try {
      text = stripFrontmatter(fs.readFileSync(path.join(root, ".cursor", "rules", `${agent.rule}.mdc`), "utf8"));
    } catch {
      text = "";
    }
  }
  if (!text) text = `Bạn là ${agent.name}, ${agent.title} của Anitech Agency.`;
  if (text.length > MAX_PERSONA_CHARS) text = text.slice(0, MAX_PERSONA_CHARS);
  cache.set(key, text);
  return text;
}

const LANGUAGES: Record<string, string> = {
  vi: "tiếng Việt",
  en: "English",
  es: "español",
  fr: "français",
  "zh-CN": "简体中文",
};

export function languageName(locale: string): string {
  return LANGUAGES[locale] ?? LANGUAGES.vi;
}

export function teamRoster(department: Department): string {
  return department.agents.map((agent) => `- ${agent.id}: ${agent.name}, ${agent.title}`).join("\n");
}

